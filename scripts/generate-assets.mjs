import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const source = new URL('../src/assets/icons/lucide/', import.meta.url);
const icons = (await readdir(source)).filter((file) => file.endsWith('.svg')).sort();
const names = [];
const symbols = [];
for (const file of icons) {
  const name = file.replace(/\.svg$/, '');
  if (!/^[a-z0-9-]+$/.test(name)) throw new Error(`Invalid icon name: ${name}`);
  const svg = await readFile(new URL(file, source), 'utf8');
  const body = svg.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!body || /<script|\bon\w+=|href=/i.test(body)) throw new Error(`Invalid icon SVG: ${file}`);
  names.push(name);
  symbols.push(`<symbol id="icon-${name}" viewBox="0 0 24 24">${body.trim()}</symbol>`);
}
await mkdir(new URL('../public/icons/', import.meta.url), { recursive: true });
await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
await writeFile(
  new URL('../public/icons/sprite.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide / Feather; see /icons/LICENSE.txt -->${symbols.join('')}</svg>\n`,
);
await writeFile(
  new URL('../src/generated/icons.ts', import.meta.url),
  `// Generated by scripts/generate-assets.mjs.\nexport const iconNames = ${JSON.stringify(names)} as const;\nexport type IconName = (typeof iconNames)[number];\n`,
);
const favicon = await readFile(new URL('../public/favicon.svg', import.meta.url));
for (const size of [192, 512]) {
  await sharp(favicon)
    .resize(size, size)
    .png()
    .toFile(new URL(`../public/icons/icon-${size}.png`, import.meta.url).pathname);
}
console.log(`Generated ${names.length} Lucide symbols and manifest icons.`);
